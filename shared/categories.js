/** 是否是合法的一级类别名 */
export function isCategory(name) {
  return CATEGORY_NAMES.includes(name);
}

/**
 * 按关键词匹配类别（用于规则兜底，LLM 正常时只作为校验后的补充）。
 * @param {string} text 归一化后的文本
 * @returns {{category:string, subcategory:string, score:number}|null}
 */
export function matchCategoryByKeyword(text) {
  if (!text) return null;
  const t = text.toLowerCase();
  let best = null;
  for (const def of CATEGORY_TREE) {
    for (const kw of def.keywords) {
      const k = kw.toLowerCase();
      if (!k) continue;
      if (!t.includes(k)) continue;
      // 关键词越长越具体，优先级越高
      const score = k.length * 10 + (def.kind === 'income' ? 0 : 1);
      if (!best || score > best.score) {
        best = { category: def.name, subcategory: guessSub(def, t), score };
      }
    }
  }
  return best;
}


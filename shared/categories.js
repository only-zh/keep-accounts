/** 前端下拉/筛选用的扁平列表 */
export function flatCategories() {
  const out = [];
  for (const def of CATEGORY_TREE) {
    out.push({ name: def.name, icon: def.icon, kind: def.kind, sub: '' });
    for (const s of def.subs) out.push({ name: def.name, icon: def.icon, kind: def.kind, sub: s });
  }
  return out;
}
